    @Published var currentLanguage: Language = .russian
    
    // MARK: - Supported Languages
    
    enum Language: String, CaseIterable {
        case russian = "ru"
        case english = "en"
        case chinese = "zh-Hans"
        case arabic = "ar"
        
        var displayName: String {
            switch self {
            case .russian: return "Русский"
            case .english: return "English"
            case .chinese: return "中文"
            case .arabic: return "العربية"
            }
        }
        
        var flag: String {
            switch self {
            case .russian: return "🇷🇺"
            case .english: return "🇬🇧"
            case .chinese: return "🇨🇳"
            case .arabic: return "🇦🇪"
            }
        }
        
        var isRTL: Bool {
            switch self {
            case .arabic: return true
            default: return false
            }
        }
    }
    
    // MARK: - Init
    
    init() {
        // ✅ СНАЧАЛА проверяем сохранённый язык
        if let savedLanguage = UserDefaults.standard.string(forKey: AppConfig.UserDefaultsKeys.appLanguage),
           let language = Language(rawValue: savedLanguage) {
            currentLanguage = language
        } else if let systemLanguage = Locale.current.languageCode,
                  let language = Language(rawValue: systemLanguage) {
            // Если сохранённого нет, используем системный
            currentLanguage = language
        } else {
            // По умолчанию русский
            currentLanguage = .russian
        }
    }
    
    // MARK: - Change Language
    
    /**
     * Сменить язык приложения
     */
    func changeLanguage(to language: Language) {
        // ✅ Обновляем текущий язык (это обновит UI через @Published)
        currentLanguage = language
        
        // Сохраняем язык
        // TODO: В будущем заменить на Keychain для безопасности
        UserDefaults.standard.set(language.rawValue, forKey: AppConfig.UserDefaultsKeys.appLanguage)
        
        // Синхронизируем с системой
        UserDefaults.standard.synchronize()
        
        print("✅ Language changed to: \(language.displayName)")
    }
    
    /**
     * Получить Locale для применения в приложении
     */
    var locale: Locale {
        Locale(identifier: currentLanguage.rawValue)
    }
    
